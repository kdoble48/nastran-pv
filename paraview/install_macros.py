"""Install the nastran-pv views as ParaView toolbar macros.

    python paraview/install_macros.py            # install / update
    python paraview/install_macros.py --remove   # remove them again

Each macro is a short stub in ParaView's user macro folder that imports
``nastran_views`` from the folder this script is in (a checkout's ``paraview/``, or
``nastran_pv/paraview`` of an installed package), so updating the checkout or
``pip install -U nastran-pv`` updates the macros; a new environment needs them
installed again. Restart ParaView (or use Macros > Import) after installing.

ParaView lists the macros by file name, so a label starts with the word for what the button does
(Check, Color, Overlay, Result, ...) and the toolbar keeps each kind together. Installing also
removes the stubs this script wrote under labels it no longer has (a renamed or merged button);
a file that does not start with the stub's first line is never written over or removed.
"""
import argparse
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PREFIX = "NPV "
MACROS = {  # label -> the name nastran_views.run_macro takes; in toolbar order
    "Check Model": "check", "Check Parts": "parts",
    "Clear View": "clear",
    "Color Element Type": "elementtype", "Color Family": "family", "Color Group": "group",
    "Color Indexed": "index_colors", "Color MID": "mid", "Color NSM": "nsm", "Color PID": "pid",
    "Color Thickness": "thickness",
    "Diff": "diff", "Diff End": "single", "Diff Side by Side": "side_by_side",
    "Grow from Selection": "grow_from_selection",
    "Hide Listed": "hide_file", "Hide Reached": "hide_reached", "Hide Selected": "hide_selected",
    "Highlight Listed": "highlight_file",
    "Mode Animate": "animate_mode", "Mode Animate All": "animate_modes", "Mode Save GIFs": "save_mode_animations",
    "Overlay Beams": "beams", "Overlay Bush Rotations": "bushrotations", "Overlay Bushes": "bushes",
    "Overlay Loads": "loads", "Overlay Masses": "masses", "Overlay Rigid": "rigid", "Overlay SPC": "spc",
    "Path from Selection": "path_from_selection",
    "Result Displacement": "results", "Result Forces": "forces", "Result Plies": "plies",
    "Result Random RMS": "random", "Result Random Sweep": "randomsweep", "Result Stress": "stress",
    "Show All": "show_all", "Show Only Listed": "show_only_file", "Show Only Material": "show_only_material",
    "Show Only Property": "show_only_property", "Show Only Reached": "show_only_reached",
    "Show Only Selected": "show_only_selected",
}
MARKER = "# Generated by nastran-pv"
STUB = '''# Generated by nastran-pv paraview/install_macros.py - safe to delete.
import sys
_p = r"{path}"
if _p not in sys.path:
    sys.path.insert(0, _p)
_b, sys.dont_write_bytecode = sys.dont_write_bytecode, True  # no __pycache__ in an installed package
import nastran_views
sys.dont_write_bytecode = _b
nastran_views.run_macro("{view}")
'''


def macro_dir() -> Path:
    """ParaView's user macro folder: ``Macros`` next to its settings ini, which is
    ``QSettings(IniFormat, UserScope, "ParaView")`` (ParaView 6.0 ``pqApplicationCore::settings``,
    ``pqCoreUtilities::getParaViewUserDirectory``, ``pqPythonMacroSupervisor``). Qt puts that under
    %APPDATA% on Windows, and under $XDG_CONFIG_HOME or ~/.config on Linux *and* macOS, where Qt
    keeps its non-XDG path for INI files (qsettings.cpp ``make_user_path``): not ~/Library."""
    if sys.platform.startswith("win"):
        base = Path(os.environ.get("APPDATA") or Path.home() / "AppData" / "Roaming")
    else:
        xdg = os.environ.get("XDG_CONFIG_HOME") or ""  # unset or empty: ~/.config
        if sys.platform == "darwin":
            base = Path.home() / (xdg or ".config")  # qsettings.cpp: a relative value is under ~
        else:  # qstandardpaths_unix.cpp follows the XDG spec: a relative value is ignored
            base = Path(xdg) if os.path.isabs(xdg) else Path.home() / ".config"
    return base / "ParaView" / "Macros"


def is_generated(path: Path) -> bool:
    """True for a stub this script wrote (its first line), whatever its label."""
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.readline().startswith(MARKER)
    except OSError:
        return False


def generated(folder: Path) -> list[Path]:
    """The nastran-pv stubs in ``folder``, also those of labels this version no longer has."""
    return [p for p in sorted(folder.glob(f"{PREFIX}*.py")) if is_generated(p)] if folder.is_dir() else []


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--remove", action="store_true")
    ap.add_argument("--dir", default=None, help="macro folder (default: ParaView's user folder)")
    args = ap.parse_args()
    target = Path(args.dir) if args.dir else macro_dir()
    wanted = {f"{PREFIX}{label}.py" for label in MACROS}
    for p in generated(target):
        if args.remove or p.name not in wanted:
            p.unlink()
            print(f"removed {p}" + ("" if args.remove else " (its button was renamed or merged)"))
    if args.remove:
        return 0
    target.mkdir(parents=True, exist_ok=True)
    for label, view in MACROS.items():
        p = target / f"{PREFIX}{label}.py"
        if p.exists() and not is_generated(p):
            print(f"kept {p}: not written by nastran-pv, so the {label} button is not installed")
            continue
        p.write_text(STUB.format(path=str(HERE), view=view))
        print(f"wrote {p}")
    print("Restart ParaView: the macros appear in the Macros toolbar/menu.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
