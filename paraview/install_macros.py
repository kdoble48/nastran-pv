"""Install the nastran-pv views as ParaView toolbar macros.

    python paraview/install_macros.py            # install / update
    python paraview/install_macros.py --remove   # remove them again

Each macro is a three-line stub in ParaView's user macro folder that imports
``nastran_views`` from this checkout, so updating the repository updates the
macros. Restart ParaView (or use Macros > Import) after installing.
"""
import argparse
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PREFIX = "NPV "
MACROS = {
    "Masses": "masses", "Bushes": "bushes", "Bush Rotations": "bushrotations", "Beams": "beams", "Loads": "loads", "SPC": "spc", "Rigid": "rigid",
    "Family": "family", "Group": "group", "PID": "pid", "MID": "mid", "Element Type": "elementtype",
    "Thickness": "thickness", "NSM": "nsm", "Results": "results", "Random RMS": "random",
    "Random Sweep": "randomsweep", "Animate Mode": "animate_mode",
    "Stop Mode Animation": "stop_mode_animation", "Animate All Modes": "animate_modes", "Save Mode Animations": "save_mode_animations",
    "Index Colors": "index_colors",
    "Parts": "parts", "Grow": "grow", "Grow from Selection": "grow_from_selection",
    "Path from Selection": "path_from_selection", "Model Check": "check",
    "Show Only": "show_only_selected", "Hide": "hide_selected", "Show All": "show_all", "Clear": "clear",
    "Only Property": "show_only_property", "Only Material": "show_only_material",
    "Show Only Reached": "show_only_reached", "Hide Reached": "hide_reached",
    "Show Only File": "show_only_file", "Hide File": "hide_file", "Highlight File": "highlight_file",
    "Diff": "diff", "Side by Side": "side_by_side",
    "Forces": "forces", "Stress": "stress",
}
STUB = '''# Generated by nastran-pv paraview/install_macros.py - safe to delete.
import sys
_p = r"{path}"
if _p not in sys.path:
    sys.path.insert(0, _p)
import nastran_views
nastran_views.run_macro("{view}")
'''


def macro_dir() -> Path:
    if sys.platform.startswith("win"):
        base = Path(os.environ.get("APPDATA", Path.home() / "AppData" / "Roaming"))
    else:
        base = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))
    return base / "ParaView" / "Macros"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--remove", action="store_true")
    ap.add_argument("--dir", default=None, help="macro folder (default: ParaView's user folder)")
    args = ap.parse_args()
    target = Path(args.dir) if args.dir else macro_dir()
    if args.remove:
        for label in MACROS:
            p = target / f"{PREFIX}{label}.py"
            if p.exists():
                p.unlink()
                print(f"removed {p}")
        return 0
    target.mkdir(parents=True, exist_ok=True)
    for label, view in MACROS.items():
        p = target / f"{PREFIX}{label}.py"
        p.write_text(STUB.format(path=str(HERE), view=view))
        print(f"wrote {p}")
    print("Restart ParaView: the macros appear in the Macros toolbar/menu.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
