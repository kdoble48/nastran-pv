"""CLI launchers around the ParaView executables: ``view``, ``render``, ``setup``."""
from __future__ import annotations

import os
import subprocess
import sys
import tempfile
from pathlib import Path

from .locate import STORE_PYTHON, find_executable, paraview_scripts_dir, store_python


def nsm_set_id(text: str) -> int:
    """argparse type for ``--nsm-set``: a set id, or 0 for none."""
    import argparse

    value = int(text)
    if value < 0:
        raise argparse.ArgumentTypeError("give a set id, or 0 for none (leave it out for Case Control NSM=)")
    return value

# Batch pvpython needs no window on screen. pvpython reads its own options only before the script.
# Verified on Windows (ParaView 5.13.1 and 6.0); `render --onscreen` is the way back where a build
# cannot render offscreen.
OFFSCREEN = "--force-offscreen-rendering"


def shell_join(cmd) -> str:
    """A command line that can be pasted into this platform's shell (paths with spaces quoted)."""
    if sys.platform.startswith("win"):
        return subprocess.list2cmdline([str(c) for c in cmd])
    import shlex

    return shlex.join(str(c) for c in cmd)

VIEW_NAMES = ("masses", "bushes", "bushrotations", "beams", "loads", "spc", "rigid", "family", "group", "pid", "mid",
              "elementtype", "thickness", "nsm", "results", "random", "randomsweep", "parts", "check", "diff",
              "forces", "stress", "plies", "none")

GUI_SCRIPT = """\
# generated by `nastran-pv view`
import sys
sys.path.insert(0, {scripts!r})
_b, sys.dont_write_bytecode = sys.dont_write_bytecode, True  # no __pycache__ in an installed package
import nastran_views as nv
sys.dont_write_bytecode = _b
if {against!r}:
    nv.load_reader({against!r})  # the reference model (A) of the diff and side_by_side
reader = nv.load_reader({deck!r}, {results!r}, {nsm_set!r}, {random!r})
if {view!r} != "none":
    nv.apply({view!r}, reader=reader)
else:
    from paraview import simple as pv
    pv.Show(reader)
    pv.ResetCamera()
"""


def gui_script(deck: str, view: str, results: str | None, nsm_set: int | None = None,
               random: dict | None = None, against: str | None = None) -> str:
    return GUI_SCRIPT.format(scripts=str(paraview_scripts_dir()), deck=str(Path(deck).resolve()),
                             results=str(Path(results).resolve()) if results else None, nsm_set=nsm_set,
                             view=view, random=random, against=str(Path(against).resolve()) if against else None)


def random_options(args) -> dict | None:
    """The view/render --random options as ``nastran_views.load_reader``'s ``random``."""
    asd = getattr(args, "random", None)
    if not asd:
        return None
    if Path(asd).suffix and Path(asd).is_file():
        asd = str(Path(asd).resolve())
    return {"asd": asd, "drive": args.drive, "damping": args.damping, "g": args.g, "frames": args.random_frames}


def add_random_arguments(p) -> None:
    """--random/--drive/--damping/--g/--random-frames (convert, stats, store add, view, render)."""
    p.add_argument("--random", metavar="ASD", help='random response from the --results modes: base-acceleration '
                                                  'ASD (unit^2/Hz) as a two-column CSV/text file or '
                                                  '"20:0.01,80:0.04,2000:0.007"')
    p.add_argument("--drive", choices=("X", "Y", "Z"), default="Z", type=str.upper, help="drive axis (basic)")
    p.add_argument("--damping", type=float, default=0.05, metavar="ZETA",
                   help="modal critical-damping ratio (default 0.05, Q = 10)")
    p.add_argument("--g", type=float, default=None, metavar="VALUE",
                   help="model length/s^2 per input acceleration unit (9806.65 for g in mm): adds DispRMS")
    p.add_argument("--random-frames", type=int, default=100, metavar="N",
                   help="log-spaced frequency frames (plus one per mode), default 100")


MODEL_FILES = (".vtm", ".pvd", ".vtkhdf", ".hdf")  # converted models: opened with ParaView's own readers


def _check_inputs(args) -> None:
    """Fail here, with a clear message, instead of inside ParaView."""
    for label, value in (("deck", args.deck), ("results file", getattr(args, "results", None)),
                         ("reference model", getattr(args, "against", None))):
        if value and not Path(value).is_file():
            raise SystemExit(f"nastran-pv: {label} not found: {Path(value).resolve()}")
    if Path(args.deck).suffix.lower() in MODEL_FILES:
        flags = [f for f, v in (("--results", getattr(args, "results", None)),
                                ("--nsm-set", getattr(args, "nsm_set", None)),
                                ("--random", getattr(args, "random", None) or None)) if v is not None]
        if flags:
            raise SystemExit(f"nastran-pv: {' and '.join(flags)} need the deck; {Path(args.deck).name} is "
                             f"already converted (convert it again with {' '.join(flags)})")


def cmd_view(args) -> int:
    """Open the ParaView GUI with the plugin loaded, the deck open and a view applied."""
    _check_inputs(args)
    exe = Path(args.paraview) if args.paraview else find_executable("paraview")
    fd, script = tempfile.mkstemp(prefix="nastran_pv_view_", suffix=".py")
    with os.fdopen(fd, "w") as f:
        f.write(gui_script(args.deck, args.view, args.results, nsm_set=args.nsm_set, random=random_options(args),
                           against=args.against))
    cmd = [str(exe), f"--script={script}"]
    if args.dry_run:
        print(shell_join(cmd))
        print(Path(script).read_text())
        return 0
    kwargs = {"creationflags": 0x00000008} if sys.platform.startswith("win") else {"start_new_session": True}
    subprocess.Popen(cmd, **kwargs)  # detached: the shell returns while ParaView runs
    print(f"launched {exe.name} with {Path(args.deck).name} ({args.view} view)")
    return 0


def cmd_render(args) -> int:
    """Batch screenshots through pvpython + render_model.py."""
    _check_inputs(args)
    exe = Path(args.pvpython) if args.pvpython else find_executable("pvpython")
    cmd = [str(exe), *([] if args.onscreen else [OFFSCREEN]), str(paraview_scripts_dir() / "render_model.py"),
           str(Path(args.deck).resolve()), "--out", args.out, "--size", *map(str, args.size), "--preset", *args.preset, "--views", *args.views]
    if args.results:
        cmd += ["--op2", str(Path(args.results).resolve())]
    cmd += ["--step", str(args.step)]  # also picks the step of a converted series
    if args.nsm_set is not None:
        cmd += ["--nsm-set", str(args.nsm_set)]
    if args.against:
        cmd += ["--against", str(Path(args.against).resolve())]
    rnd = random_options(args)
    if rnd:
        cmd += ["--random", rnd["asd"], "--drive", rnd["drive"], "--damping", str(rnd["damping"]),
                "--random-frames", str(rnd["frames"])] + (["--g", str(rnd["g"])] if rnd["g"] else [])
    if args.dry_run:
        print(shell_join(cmd))
        return 0
    return subprocess.call(cmd)


def cmd_setup(args) -> int:
    """Vendor pyNastran & co. for ParaView's Python and install the toolbar macros."""
    if store_python():
        if not args.dry_run:
            raise SystemExit(f"nastran-pv setup: {STORE_PYTHON}")
        print(f"warning: {STORE_PYTHON}")
    scripts = paraview_scripts_dir()
    plugin = scripts / "nastran_bdf_reader.py"
    print(f"plugin: {plugin}")
    try:
        pvpython = args.pvpython or str(find_executable("pvpython"))
    except FileNotFoundError as exc:
        if not args.dry_run:
            raise
        print(f"warning: {exc}; showing the commands with <pvpython>")
        pvpython = "<pvpython>"
    steps = [[sys.executable, str(scripts / "install_deps.py"), "--pvpython", pvpython]]
    if not args.no_macros:
        steps.append([sys.executable, str(scripts / "install_macros.py")])
    for cmd in steps:
        print("+", shell_join(cmd), flush=True)  # before the child writes
        if not args.dry_run and subprocess.call(cmd) != 0:
            return 1
    print(f"Done. Start ParaView and load the plugin once (Tools > Manage Plugins > Load New: {plugin}, "
          "tick Auto Load), or use `nastran-pv view`.")
    return 0


def add_parsers(sub) -> None:
    v = sub.add_parser("view", help="open the ParaView GUI on a deck with a ready-made view")
    v.add_argument("deck", help="run deck, bulk-data file, or a .vtm/.vtkhdf/.pvd written by nastran-pv convert")
    v.add_argument("--view", default="pid", choices=VIEW_NAMES)
    v.add_argument("--results", "--op2", dest="results", help="OP2 or MSC HDF5 (.h5) results file")
    v.add_argument("--nsm-set", type=nsm_set_id, default=None, metavar="ID", help="bulk NSM set (0 = none)")
    add_random_arguments(v)
    v.add_argument("--against", metavar="A", help="also open reference model A (for --view diff and side_by_side)")
    v.add_argument("--paraview", help="path to the paraview executable")
    v.add_argument("--dry-run", action="store_true", help="print the command and script instead of launching")
    v.set_defaults(func=cmd_view)

    r = sub.add_parser("render", help="batch screenshots via pvpython")
    r.add_argument("deck", help="run deck, bulk-data file, or a .vtm/.vtkhdf/.pvd written by nastran-pv convert")
    r.add_argument("--preset", nargs="+", default=["family", "masses", "loads", "spc"],
                   choices=[n for n in VIEW_NAMES if n != "none"])
    r.add_argument("--views", nargs="+", default=["iso"], choices=["iso", "top", "front", "side", "showcase"])
    r.add_argument("--out", default="shots")
    r.add_argument("--size", nargs=2, type=int, default=[1600, 1000])
    r.add_argument("--results", "--op2", dest="results")
    r.add_argument("--step", type=int, default=0,
                   help="0-based result step: of --results, or of a converted series")
    r.add_argument("--nsm-set", type=nsm_set_id, default=None, metavar="ID", help="bulk NSM set (0 = none)")
    add_random_arguments(r)
    r.add_argument("--against", metavar="A", help="reference model A (for --preset diff)")
    r.add_argument("--pvpython", help="path to pvpython")
    r.add_argument("--onscreen", action="store_true",
                   help="render in a visible window (default: offscreen; use this if offscreen PNGs come out blank)")
    r.add_argument("--dry-run", action="store_true")
    r.set_defaults(func=cmd_render)

    s = sub.add_parser("setup", help="install ParaView-side dependencies and toolbar macros")
    s.add_argument("--pvpython", help="path to pvpython")
    s.add_argument("--no-macros", action="store_true")
    s.add_argument("--dry-run", action="store_true")
    s.set_defaults(func=cmd_setup)
