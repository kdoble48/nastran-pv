def _mystran_bulk(src, dst) -> None:
    """Write bulk-data include ``src`` as MYSTRAN 19 runs it: CQUADR as CQUAD4 and PSHELL MID4
    blanked (MYSTRAN 19 runs neither); other files are copied."""
    text = Path(src).read_text(encoding="latin-1")
    if "CQUADR" not in text and "PSHELL" not in text:
        shutil.copyfile(src, dst)
        return
    from pyNastran.bdf.bdf import BDF

    model = BDF(debug=None)
    model.read_bdf(str(src), xref=False, punch=True)
    for eid, e in list(model.elements.items()):
        if e.type == "CQUADR":
            del model.elements[eid]
            model.add_cquad4(eid, e.pid, e.node_ids, theta_mcid=e.theta_mcid, zoffset=e.zoffset, tflag=e.tflag,
                             T1=e.T1, T2=e.T2, T3=e.T3, T4=e.T4)
    for prop in model.properties.values():
        if prop.type == "PSHELL":
            prop.mid4 = None
    model.write_bdf(str(dst))


def ucrm9_for_mystran(run_deck, out_dir) -> Path:
    """Copy the uCRM-9 static run deck and its includes into ``out_dir`` as MYSTRAN 19 solves them
    (``_mystran_bulk``), asking for ``UCRM9_REQUESTS``; returns the run deck's copy. The scenes show
    the original deck with the copy's OP2 (the results are keyed by grid and element id)."""
    run_deck, out_dir = Path(run_deck), Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    lines = []
    for line in run_deck.read_text(encoding="latin-1").splitlines():
        include = re.match(r"\s*INCLUDE\s+'([^']+)'", line, re.I)
        if include:
            name = include.group(1)
            _mystran_bulk(run_deck.parent / name, out_dir / Path(name).name)
            line = f"INCLUDE '{Path(name).name}'"
        elif re.match(r"\s*STRAIN\s*=", line, re.I):
            continue
        elif re.match(r"\s*BEGIN\s+BULK", line, re.I):
            lines += list(UCRM9_REQUESTS)
        elif re.fullmatch(r"\s*PARAM\s*,\s*K6ROT\s*,\s*1e5\s*", line, re.I):
            line = "PARAM,K6ROT,1.e5"  # MYSTRAN 19 rejects a real without a decimal point
        lines.append(line)
    copy = out_dir / run_deck.name
    copy.write_text("\n".join(lines) + "\n", encoding="latin-1")
    return copy


def model_tools_reproduce(deck: str, view_args: dict) -> dict:
    """Reproduce lines for views shown with non-default settings: the CLI arrays, then the GUI call."""
    out = {}
    for view, args in view_args.items():
        if view == "grow":
            cli = f'--grow "{args["seeds"]}"'
            call = f'seeds="{args["seeds"]}"'
        else:
            cli = f'--parts --rules "exclude={",".join(args["exclude"])}"'
            call = f"exclude={args['exclude']!r}".replace("'", '"')
        out[view] = [f"nastran-pv convert {deck} {cli} -o out/{view}.vtm",
                     f'# ParaView Python shell: nastran_views.apply("{view}", {call})']
    return out


def build_models(ucrm9, demo_bdf, demo_op2, solved=None) -> list[dict]:
    """The models.json list for export_site.py. ``solved`` holds the MYSTRAN static solves of the
    result scenes, each skipped without its entry: ``"ucrm9"`` {"results": OP2, "body": the free
    body's seeds}, ``"tray"`` and ``"plate"`` (deck, OP2)."""
    solved = solved or {}
    models = []
    if ucrm9:
        view_args = {"grow": {"seeds": UCRM9_ROOT_RIB}, "parts": {"exclude": ["rigid"]}}
        models.append({"id": "ucrm9", "title": "uCRM-9 wingbox", "deck": str(ucrm9), "results": None,
                       "views": ["masses", "loads", "spc", "rigid", "family", "group", "pid", "mid",
                                 "elementtype", "thickness", "grow", "parts"], "credit": UCRM9_CREDIT,
                       "view_args": view_args,
                       "reproduce": model_tools_reproduce(Path(ucrm9).name, view_args)})
        static = solved.get("ucrm9")
        if static:
            body = {"seeds": static["body"], "label": f"the wing outboard of y = {UCRM9_CUT_Y:g} m"}
            models.append({"id": "ucrm9static", "title": "uCRM-9 wingbox, static cruise (MYSTRAN)", "deck": str(ucrm9),
                           "results": str(static["results"]),
                           "views": ["results", "forces", "stress", "spcforces", "mpcforces", "oload", "freebody",
                                     "average"],
                           "view_args": {"freebody": body}, "captions": RESULT_CAPTIONS["ucrm9static"],
                           "credit": UCRM9_STATIC_CREDIT})
    views = ["bushes", "bushrotations", "beams", "masses", "nsm", "check"] + (["results"] if demo_op2 else [])
    models.append({"id": "demo", "title": "Demo: tray on four isolators", "deck": str(demo_bdf),
                   "results": str(demo_op2) if demo_op2 else None, "views": views, "credit": DEMO_CREDIT})
    if solved.get("tray"):
        deck, op2 = solved["tray"]
        models.append({"id": "tray", "title": "Demo: tray under 1 g and a pressure (static)", "deck": str(deck),
                       "results": str(op2), "views": ["loads", "results", "forces", "stress"],
                       "captions": RESULT_CAPTIONS["tray"], "credit": TRAY_CREDIT})
    if solved.get("plate"):
        deck, op2 = solved["plate"]
        models.append({"id": "plate", "title": "Demo: composite plate", "deck": str(deck), "results": str(op2),
                       "views": ["plies"], "view_args": {"plies": {"ply": 2, "quantity": "stress"}},
                       "captions": RESULT_CAPTIONS["plate"], "credit": PLATE_CREDIT})
    return models


def outboard_pids(deck, y) -> list[int]:
    """The PIDs whose elements have every grid at a span (basic y) of at least ``y``."""
    from nastran_pv.deck import load_deck

    model = load_deck(str(deck), echo=False).model
    inboard, seen = set(), set()
    for elem in model.elements.values():
        pid = getattr(elem, "pid", None)
        if pid is None:
            continue
        seen.add(pid)
        if min(model.nodes[n].xyz[1] for n in elem.node_ids if n) < y:
            inboard.add(pid)
    return sorted(seen - inboard)


def solve_results(ucrm9, mystran, out) -> dict:
    """Write and solve the static decks of the result scenes with MYSTRAN, each in its own folder
    under ``out`` (MYSTRAN writes a dozen side files): ``build_models``' ``solved``."""
    md = _make_demo()
    solved = {"tray": None, "plate": None}
    for key, write, name in (("tray", md.write_demo_static, "demo_static.bdf"),
                             ("plate", md.write_composite_plate, "composite_plate.bdf")):
        (out / key).mkdir(parents=True, exist_ok=True)
        deck = write(out / key / name)
        solved[key] = (deck, md.solve(deck, mystran))
    if ucrm9:
        copy = ucrm9_for_mystran(ucrm9, out / "ucrm9-mystran")
        print(f"solving uCRM-9 static with MYSTRAN ({copy.parent})")
        pids = outboard_pids(ucrm9, UCRM9_CUT_Y)
        solved["ucrm9"] = {"results": md.solve(copy, mystran), "body": "PID " + " ".join(map(str, pids))}
    return solved


def pvpython_command(pvpython, models_json, out_dir) -> list[str]:
    """Export every view offscreen: no ParaView window opens on the desktop."""
    from nastran_pv.launch import OFFSCREEN

    return [str(pvpython), OFFSCREEN, str(ROOT / "paraview" / "export_site.py"), str(models_json), str(out_dir)]


def crop_thumbnail(src, dst, size=(800, 500), margin=0.06, threshold=8) -> None:
    """Crop to the non-white pixels, pad to the ``size`` aspect ratio with white, resize."""
    im = Image.open(src).convert("RGB")
    diff = ImageChops.difference(im, Image.new("RGB", im.size, (255, 255, 255))).convert("L")
    x0, y0, x1, y1 = diff.point(lambda v: 255 if v > threshold else 0).getbbox() or (0, 0, *im.size)
    w, h = (x1 - x0) * (1 + 2 * margin), (y1 - y0) * (1 + 2 * margin)
    aspect = size[0] / size[1]
    w, h = (h * aspect, h) if w / h < aspect else (w, w / aspect)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    box = [round(cx - w / 2), round(cy - h / 2), round(cx + w / 2), round(cy + h / 2)]
    canvas = Image.new("RGB", (box[2] - box[0], box[3] - box[1]), (255, 255, 255))
    part = im.crop((max(box[0], 0), max(box[1], 0), min(box[2], im.width), min(box[3], im.height)))
    canvas.paste(part, (max(-box[0], 0), max(-box[1], 0)))
    canvas.resize(size, Image.LANCZOS).save(dst)


def validate_scene(path) -> set[str]:
    """Class names in a .vtksz; ValueError unless it has an actor, polydata and data arrays."""
    with zipfile.ZipFile(path) as z:
        state = json.loads(z.read("index.json"))
    classes, indexed, stack = set(), False, [state["scene"]]
    while stack:
        node = stack.pop()
        classes.add(node.get("type"))
        indexed |= bool(node.get("properties", {}).get("indexedLookup"))
        stack.extend(node.get("dependencies", []))
    if not any(c and c.endswith("Actor") for c in classes):
        raise ValueError(f"{Path(path).name}: no actors in scene")
    if indexed:
        raise ValueError(f"{Path(path).name}: indexed lookup in scene (vtk.js cannot render it)")
    if "vtkPolyData" not in classes or not state.get("hashes"):
        raise ValueError(f"{Path(path).name}: no geometry data in scene")
    return classes


def collect_manifest(out_dir, commit) -> dict:
    views = [json.loads(p.read_text(encoding="utf-8")) for p in Path(out_dir).glob("*.json")
             if p.name not in ("manifest.json", "models.json")]
    rank = {m: i for i, m in enumerate(MODEL_ORDER)}
    views.sort(key=lambda v: (rank.get(v["model"], 99), VIEW_ORDER.index(v["view"])))
    now = dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")
    return {"generated": now, "commit": commit, "views": views}


def listed_files(manifest) -> list[str]:
    names = []
    for v in manifest["views"]:
        names += [v["png"], v["thumb"], v["scene"]]
        for fr in v.get("frames", []):
            names += [fr["png"], fr["scene"]]
    return sorted(set(names))


def pack(out_dir, manifest, zip_path) -> list[str]:
    out_dir = Path(out_dir)
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    names = listed_files(manifest) + ["manifest.json"]
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for name in names:
            z.write(out_dir / name, name)
    return names


def _make_demo():
    spec = importlib.util.spec_from_file_location("make_demo", ROOT / "docs" / "models" / "make_demo.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _git_commit() -> str:
    r = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True)
    return r.stdout.strip() or "unknown"


def upload(zip_path) -> None:
    if subprocess.run(["gh", "release", "view", RELEASE], cwd=ROOT, capture_output=True).returncode:
        subprocess.run(["gh", "release", "create", RELEASE, "--title", "Gallery assets", "--latest=false",
                        "--notes", "Generated by docs/build_gallery.py; downloaded by the docs workflow."],
                       cwd=ROOT, check=True)
    subprocess.run(["gh", "release", "upload", RELEASE, str(zip_path), "--clobber"], cwd=ROOT, check=True)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ucrm9", type=Path, help="uCRM-9 coarse run deck (skipped if omitted)")
    ap.add_argument("--mystran", type=Path, help="MYSTRAN executable (results view skipped if omitted)")
    ap.add_argument("--pvpython", type=Path)
    ap.add_argument("--out", type=Path, default=OUT,
                    help="output folder, emptied first (default build/gallery); the zip goes next to it")
    ap.add_argument("--upload", action="store_true", help=f"replace the asset on the '{RELEASE}' release")
    args = ap.parse_args(argv)

    from nastran_pv.locate import find_executable

    if args.ucrm9 and not args.ucrm9.exists():
        ap.error(f"uCRM-9 deck not found: {args.ucrm9}")
    pvpython = args.pvpython or find_executable("pvpython")
    out = args.out.resolve()
    zip_path = ZIP if args.out == OUT else out.parent / ZIP.name
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    md = _make_demo()
    demo_bdf = md.write_demo(out / "demo.bdf")
    demo_op2, solved = None, {}
    if args.mystran:
        demo_op2 = md.solve(demo_bdf, args.mystran)
        solved = solve_results(args.ucrm9, args.mystran, out / "solve")
    else:
        print("no --mystran: the result scenes (demo modes, static results, plies) skipped")
    models_json = out / "models.json"
    models_json.write_text(json.dumps(build_models(args.ucrm9, demo_bdf, demo_op2, solved), indent=1),
                           encoding="utf-8")
    rc = subprocess.run(pvpython_command(pvpython, models_json, out), cwd=ROOT).returncode
    if rc:
        print(f"export failed (exit {rc})")
        return rc
    manifest = collect_manifest(out, _git_commit())
    for v in manifest["views"]:
        crop_thumbnail(out / v["thumb_raw"], out / v["thumb"])
        for scene in [v["scene"]] + [fr["scene"] for fr in v.get("frames", [])]:
            validate_scene(out / scene)
            size = (out / scene).stat().st_size
            if size > SCENE_WARN_BYTES:
                print(f"warning: {scene} is {size / 1e6:.1f} MB (budget {SCENE_WARN_BYTES / 1e6:.0f} MB)")
    names = pack(out, manifest, zip_path)
    print(f"{len(manifest['views'])} views, {len(names)} files -> {zip_path} "
          f"({zip_path.stat().st_size / 1e6:.1f} MB)")
    if args.upload:
        upload(zip_path)
        print(f"uploaded to release '{RELEASE}'")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
