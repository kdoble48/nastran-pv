"""Generate the docs gallery assets and (optionally) upload them as a GitHub release asset.

    python docs/build_gallery.py --ucrm9 <path to run_uCRM-9_static_cruise_coarse.bdf>
        [--mystran tools/mystran-19.0.0-windows-x86_64.exe] [--pvpython PATH] [--out DIR] [--upload]

Steps: write the demo deck and solve its modes with MYSTRAN; write and solve the result scenes'
static decks (the demo tray under 1 g and a pressure, a composite plate, and a MYSTRAN copy of the
uCRM-9 static cruise run: ``ucrm9_for_mystran``); export every entry with pvpython
(paraview/export_site.py); crop thumbnails; validate scenes; write manifest.json; zip the listed
files to build/gallery-assets.zip (next to --out); with --upload, replace the asset on the
`gallery-assets` release. Without MYSTRAN the result scenes are skipped, without --ucrm9 the
uCRM-9 ones. MYSTRAN solves no frequency response, transient or complex run, so those result types
have no scene. Slow (pvpython, and about a minute and a half for the uCRM-9 solve): run it in the
background.
"""
